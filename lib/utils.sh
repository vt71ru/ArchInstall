#!/usr/bin/env bash
#
#============================================================
# Arch Installer
#------------------------------------------------------------
# utils.sh
#
# Общие вспомогательные функции
#
# Обязанности:
#  • Проверки
#  • Работа с файлами
#  • Безопасные команды
#  • Строковые операции
#
# Не содержит логику установки.
#============================================================

[[ -n "${UTILS_SH_LOADED:-}" ]] && return

readonly UTILS_SH_LOADED=1


#------------------------------------------------------------
# Files
#------------------------------------------------------------

file_exists()
{
    [[ -f "$1" ]]
}


directory_exists()
{
    [[ -d "$1" ]]
}


file_create()
{
    touch "$1"
}


file_append()
{
    local file="$1"
    shift

    printf '%s\n' "$@" >> "$file"
}


#------------------------------------------------------------
# Commands
#------------------------------------------------------------

command_exists()
{
    command -v "$1" >/dev/null 2>&1
}


run_command()
{
    logger_debug "Execute: $*"

    "$@"
}


#------------------------------------------------------------
# Strings
#------------------------------------------------------------

string_empty()
{
    [[ -z "$1" ]]
}


string_not_empty()
{
    [[ -n "$1" ]]
}


string_trim()
{
    local value="$1"

    value="${value#"${value%%[![:space:]]*}"}"
    value="${value%"${value##*[![:space:]]}"}"

    printf '%s' "$value"
}


#------------------------------------------------------------
# Numbers
#------------------------------------------------------------

is_number()
{
    [[ "$1" =~ ^[0-9]+$ ]]
}


clamp()
{
    local value="$1"
    local min="$2"
    local max="$3"

    (( value < min )) && {
        printf '%s' "$min"
        return
    }

    (( value > max )) && {
        printf '%s' "$max"
        return
    }

    printf '%s' "$value"
}


#------------------------------------------------------------
# System
#------------------------------------------------------------

get_hostname()
{
    hostname
}


get_username()
{
    id -un
}


#------------------------------------------------------------
# Wait
#------------------------------------------------------------

wait_key()
{
    local message="${1:-Press Enter}"

    printf '%s' "$message"

    read -r
}


sleep_ms()
{
    local ms="$1"

    sleep "0.$(printf '%03d' "$ms")"
}


#------------------------------------------------------------
# Logging helpers
#------------------------------------------------------------

debug_var()
{
    local name="$1"

    logger_debug \
        "${name}=$(config_get "$name")"
}
